/**
 * Write docs/API_ROUTES.md: every endpoint the application serves, grouped by area, and who may
 * call it.
 *
 *   npm run docs:api
 *
 * Generated rather than written, because a hand-kept list of two hundred routes is wrong within a
 * week and nobody can tell which line went stale. This reads the same census the security tests
 * read, so the document says exactly what the server enforces. `route-inventory.e2e-spec.ts` fails
 * when a route exists that this file does not mention, which is the reminder to run it again.
 *
 * It writes into docs/, which is kept outside this repository like the rest of the documentation,
 * and makes the folder on a machine that does not have it yet.
 */
import 'dotenv/config';
import { mkdirSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { NestFactory } from '@nestjs/core';
import { AppModule } from '../src/app.module';
import { configureApp } from '../src/app.setup';
import { inventoryRoutes, type RouteFact } from '../src/common/utils/route-inventory.util';

const OUT = join(__dirname, '..', '..', 'docs', 'API_ROUTES.md');

/** The area a route belongs to: the first segment after the version, or the bare path. */
function area(route: RouteFact): string {
  const match = /^\/api\/v\d+\/([^/]+)/.exec(route.path);
  return match ? match[1]! : route.path.replace(/^\/api\//, '');
}

function who(route: RouteFact): string {
  if (route.machine) return 'Machine credential';
  if (route.access === 'public') return 'Anyone, no sign-in';
  if (route.access === 'any-signed-in') return 'Any signed-in user, for their own account';
  return route.roles.join(', ');
}

async function main() {
  const app = await NestFactory.create(AppModule, { logger: false });
  configureApp(app);
  await app.init();
  const routes = inventoryRoutes(app);
  await app.close();

  const groups = new Map<string, RouteFact[]>();
  for (const route of routes) {
    const key = area(route);
    groups.set(key, [...(groups.get(key) ?? []), route]);
  }

  const lines: string[] = [
    '# API routes',
    '',
    '<!-- Generated by `npm run docs:api` in backend/. Do not edit by hand: the next run overwrites',
    '     it, and the route census test fails when a route is missing from it. -->',
    '',
    `Every endpoint the server answers, ${routes.length} in all, and who may call each one. For how`,
    'to sign in, page through a list, read an error, or connect a machine, see [API.md](API.md).',
    '',
    'Roles are checked on the server for every request. A route listed for `OPERATOR_ADMIN` is',
    "further limited to that operator's own records; the role says who may call it, not whose data",
    'comes back.',
    '',
  ];

  for (const key of [...groups.keys()].sort()) {
    lines.push(`## ${key}`, '', '| Method | Path | Who may call it |', '|---|---|---|');
    const sorted = groups
      .get(key)!
      .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
    for (const route of sorted) {
      lines.push(`| ${route.method} | \`${route.path}\` | ${who(route)} |`);
    }
    lines.push('');
  }

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, lines.join('\n'), 'utf8');
  console.log(`  Wrote ${routes.length} routes in ${groups.size} areas to docs/API_ROUTES.md`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
